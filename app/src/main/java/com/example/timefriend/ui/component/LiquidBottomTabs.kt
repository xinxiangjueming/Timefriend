/**
 * Kyant Backdrop Catalog 的 LiquidBottomTabs，1:1 移植自
 * github.com/Kyant0/AndroidLiquidGlass → app/.../catalog/components/LiquidBottomTabs.kt
 * 与 LiquidBottomTab.kt，仅包名与注释本地化。
 *
 * 官方结构（三层）：
 *  1. 容器 Row：vibrancy → blur(8dp) → lens(24dp, 24dp)，layerBlock 做按下整体放大，
 *     onDrawSurface 铺 40% 底色保证可读性；
 *  2. 不可见副本 Row（alpha(0f) + layerBackdrop(tabsBackdrop) + ColorFilter.tint）：
 *     把 tab 图标/文字单独录一层，供滑块同时折射「页面背景 + tab 内容」，
 *     并用 LocalLiquidBottomTabScale 让内容随按压 1f→1.2f 放大；
 *  3. 滑动 pill：backdrop = rememberCombinedBackdrop(页面层, tabsBackdrop)，
 *     lens(10dp,14dp, chromaticAberration = true) 做带色散的折射，
 *     Highlight / Shadow / InnerShadow 与按动进度联动，layerBlock 做速度形变，
 *     DampedDragAnimation 负责按下放大（78/56）与拖拽切 tab，
 *     InteractiveHighlight 负责跟随手指的 RuntimeShader 高光。
 *
 * 注意：禁止把整个底栏再包一层 layerBackdrop —— 会与自身 drawBackdrop 形成
 * 自采样循环，官方文档明确会触发 RenderThread SIGSEGV。
 */

